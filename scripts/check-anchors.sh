#!/usr/bin/env bash
# Один вопрос: не сдвинулись ли якоря детерминизма (docs/PLAYBOOK.md §4).
#
# Зачем прибор, а не память: в M4 организатор сверял восемь величин перед каждым
# коммитом руками — по одной команде на величину. Прибор отвечает одной командой
# и одним кодом выхода, и его же гоняет приёмщик после каждого негативного контроля.
#
# Значения ниже — те же, что в PLAYBOOK §4 и в тестах. Перепиновка якоря — только
# осознанно: правишь здесь — объясни в сообщении коммита, какая семантика изменилась,
# было A, стало B, почему. Молчаливый перепин — худшее, что может случиться с проектом
# про детерминизм.
#
# Девятый якорь — «150 контрольных точек эталона, все различны» — проверяет CI;
# здесь его нет сознательно: локальный прогон отвечает за хэши, не за раскладку точек.
#
# 2026-08-18: пять из восьми значений переприпинены ЕДИНСТВЕННЫЙ раз за историю
# проекта — вердикт владельца ADR-021 (128×72 → 160×90): змейка переехала на поле
# 20×10, эталон переигран той же длины (3000 тиков, 150 точек, все различны).
# Три digest'а тишины не сдвинулись — они функция числа тиков, не пикселей,
# и это их неподвижность доказала, что PCM-контур развязан с разрешением.
#
# 2026-09-01, ADR-041 (одна действующая версия каждого формата, номер 0): переприпинен
# РОВНО ОДИН якорь — sha256 golden.qrpr, 30ef4a9b…c031 -> 4e06d5bc…3d510. Причина точная:
# .qrpr теперь всегда пишется одной раскладкой (версия 0, расширенная шапка и оба потока),
# поэтому файл вырос с 786 байт до 810, а версия в шапке стала 0; плюс сменился
# идентификатор картриджа — банки звука пересобраны с номером версии 0. Семь остальных
# якорей НЕ сдвинулись, и это доказательство, а не совпадение: конверсия музыки v1 -> v2
# была звук-в-звук, номер версии в кадр и в PCM не входит. Сдвинься здесь хоть один хэш
# кадра или звука — это была бы другая правка, и её пришлось бы объяснять отдельно.
set -u
cd "$(dirname "$0")/.." || exit 2

DLL="src/Quarp.Cli/bin/Release/net10.0/quarp.dll"
if [ ! -f "$DLL" ]; then
  echo "нет Release-сборки ($DLL) — сначала: dotnet build -c Release" >&2
  exit 2
fi

# Какой командой звать .NET. На Linux (CI) это `dotnet`. На машине владельца прибор
# запускается через WSL-bash, а в WSL по PATH лежит НЕ `dotnet`, а `/mnt/c/Program
# Files/dotnet/dotnet.exe` — interop видит только имя с расширением. До 2026-08-25 прибор
# там вообще не запускался: «dotnet: command not found», exit 2 — то есть якоря на машине,
# где идёт вся работа, не проверялись ничем. Это тот же класс дефекта, что стоп-заглушка
# python3, из-за которой пришлось переписать check-modules.sh на awk: прибор, который не
# может запуститься у владельца, — не прибор. Переменную DOTNET можно задать снаружи.
DOTNET="${DOTNET:-}"
if [ -z "$DOTNET" ]; then
  if command -v dotnet >/dev/null 2>&1; then
    DOTNET=dotnet
  elif command -v dotnet.exe >/dev/null 2>&1; then
    DOTNET=dotnet.exe
  else
    echo "не найден ни dotnet, ни dotnet.exe — прибор не может спросить у консоли" >&2
    exit 2
  fi
fi

# Почему через `tr -d '\r'`. На машине владельца прибор идёт через WSL-bash, а зовёт
# ДОТНЕТ ВИНДОВЫЙ (dotnet.exe): его stdout — CRLF. Подстановка "$(...)" снимает последний
# перевод строки, но \r остаётся ВНУТРИ значения, и сравнение "e7005109e18c6962" с
# "e7005109e18c6962\r" даёт СДВИГ, которого нет. 2026-08-25 прибор так и отрапортовал:
# «ожидалось e7005109e18c6962, стало e7005109e18c6962» — восемь якорей, все восемь «сдвинулись»,
# все восемь совпадали посимвольно. Ложная тревога прибора о детерминизме хуже его молчания:
# в следующий раз ей не поверят. pipefail нужен, чтобы код выхода остался кодом dotnet, а не tr.
set -o pipefail
q() { "$DOTNET" "$DLL" "$@" | tr -d '\r'; }

fail=0
check() { # имя ожидание факт
  if [ "$2" = "$3" ]; then
    printf 'OK\t%s\t%s\n' "$1" "$3"
  else
    printf 'СДВИГ\t%s\tожидалось %s, стало %s\n' "$1" "$2" "$3"
    fail=1
  fi
}

sim_out="$(q sim carts/snake --ticks 600)" || exit 2
check "sim-600, кадр" "e7005109e18c6962" "$(printf '%s\n' "$sim_out" | tail -1)"
check "sim-600, звук" "368c5099da148c05" "$(printf '%s\n' "$sim_out" | awk '/^audio/{print $2}' | tail -1)"

rep_out="$(q replay play carts/snake/replays/golden.qrpr)" || exit 2
check "реплей, кадр" "77618a204fd261f7" "$(printf '%s\n' "$rep_out" | tail -1)"
check "реплей, звук" "44775c6a5b3cbaa7" "$(printf '%s\n' "$rep_out" | awk '/^audio/{print $2}' | tail -1)"

check "тишина, 0 тиков"    "cbf29ce484222325" "$(q audio silence --ticks 0    | awk '{print $2}')"
check "тишина, 600 тиков"  "54738d7161a01b25" "$(q audio silence --ticks 600  | awk '{print $2}')"
check "тишина, 3000 тиков" "220acbc2c817fb25" "$(q audio silence --ticks 3000 | awk '{print $2}')"

check "sha256 golden.qrpr" \
  "4e06d5bc95c5f84dfaf61285ba9b04779a1a33cd9a5d7a055ad284d53953d510" \
  "$(sha256sum carts/snake/replays/golden.qrpr | awk '{print $1}')"

if [ "$fail" -ne 0 ]; then
  echo
  echo "ЯКОРЯ СДВИНУЛИСЬ. Стоп и доклад (PLAYBOOK §4): не перепиновывать, разбираться."
fi
exit "$fail"
