#!/usr/bin/env bash
# Один вопрос: держатся ли границы модулей оболочки — идут ли ссылки строго в одну
# сторону, и не перерос ли какой-то файл размер, на котором он ещё делает одно дело.
#
# Зачем прибор, а не память. До этой волны у оболочки был ровно один числовой прибор —
# scripts/count-chrome.sh, — и он отвечал на вопрос «не взять ли чужой ImGui». Владелец
# 2026-08-24 снял этот вопрос с повестки («третьи стороны не привлекаем без крайней
# нужды») и поставил другой: «не пора ли отрефакторить и разделить модули, чтобы не было
# спагетти-архитектуры и каждый модуль занимался своим делом и не лез в чужое». На этот
# вопрос нельзя ответить числом строк — можно только направлением ссылок. Причём ровно
# так же, как с числом строк в волнах 2g/2h: «мне кажется, слои держатся» — это не факт,
# это память дежурного, и она разъезжается между волнами молча. Здесь у факта «кто на
# кого ссылается» появляется один постоянный владелец: таблица СЛОЁВ ниже и разбор
# исходников этим скриптом.
#
# --------------------------------------------------------------------------------------
# ЧТО ТАКОЕ СЛОЙ (решение этой волны; список файлов ниже — и есть определение, к которому
# надо придираться на ревью, а не к формулировке).
#
#   1 «документ»  — модель и чистые величины. Ни графического устройства, ни устройств
#                   ввода, ни знания о геометрии экрана. Умеет читать/писать себя на диск.
#                   Сюда же попадают чистые величины оболочки (TimeSpeed, AudioQueue,
#                   TickAccumulator, PaletteColors, ShellMode): у них нет зависимостей
#                   вообще, и они — та самая нижняя ступень, с которой читают все.
#   2 «вид»       — геометрия и состояние показа, БЕЗ устройства: раскладки, страничная
#                   математика листа, состояние флаута и подсказок, таблица иконок,
#                   геометрия «бегущих муравьёв». Проверяемая примета: тип конструируется
#                   в headless-тесте, ему не нужен GraphicsDevice.
#   3 «рендер»    — то, что владеет ресурсом устройства (GraphicsDevice/Texture2D/
#                   SpriteBatch или аудиоустройство). Читает документ и вид; на него не
#                   ссылается никто, кроме проводки и других рендереров.
#   4 «проводка»  — цикл, режимы, чтение устройств ввода, точка входа, и хозяин запущенного
#                   картриджа (CartSession: он потребляет ShellCommands, то есть ввод).
#                   Ссылается на всё; на неё не ссылается никто.
#
# ПРАВИЛО ОДНО: ссылка идёт вниз или вбок (слой N → слой M, где M <= N). Ссылка вверх
# (M > N) — нарушение, и это единственное, за что прибор возвращает 1.
#
# ГИПОТЕЗА ОРГАНИЗАТОРА И ЧТО ДЕРЕВО ЕЙ ВОЗРАЗИЛО (волна разделения модулей, 2026-08-24):
#   * CartLibrary приказ помещал в «проводку». Дерево возражает: файл сознательно свободен
#     от MonoGame («Deliberately free of MonoGame» в его же шапке), а читает его
#     LibraryRenderer — рендер. Проводка, читаемая рендером, была бы нарушением на ровном
#     месте. CartLibrary — документ (модель того, какие картриджи есть на диске).
#   * CartSession приказ не называл вовсе. Здесь он — проводка, а не документ: он берёт
#     `in ShellCommands`, то есть кадр клавиатурного ввода, и гоняет тики. См. «Расхождение»
#     в отчёте: при прочтении «CartSession = документ» появляется третье нарушение
#     (CartSession → ShellCommands), и чинится оно уже не переносом типа.
#   * PixelFontAtlas приказ помещал в «рендер» — верно, он владеет Texture2D. Но в нём же
#     жили три функции метрик текста, которые нужны раскладке ДО всякого рисования; из-за
#     этого EditorChrome (вид) читал рендер. Волна разнесла факт и текстуру:
#     PixelFontMetrics (слой 1) — владелец арифметики, PixelFontAtlas — три форвардера.
#   * ShellMode жил в файле ShellModeMachine.cs (проводка), а читал его EditorIcons (вид).
#     Перечисление из четырёх имён без единой зависимости — это словарь, не механика;
#     волна вынесла его в ShellMode.cs (слой 1). Ни один оператор не переехал.
#
# --------------------------------------------------------------------------------------
# ЧТО СЧИТАЕТСЯ «ССЫЛКОЙ» (и почему прибор при этом не врёт).
#
# Ссылка = имя типа, объявленного в ДРУГОМ файле оболочки, встреченное в КОДЕ этого файла
# как отдельное слово. Разбор устроен так:
#   * из исходника вычёркиваются построчные комментарии (//), блочные (/* */), обычные,
#     verbatim (@"...") и символьные литералы — вычёркиваются, чтобы номера строк не поехали;
#   * у интерполированных строк ($"...") ВНУТРЕННОСТИ ФИГУРНЫХ СКОБОК сохраняются: там
#     живёт настоящий код, и тип, названный только там, — настоящая ссылка;
#   * имена типов берутся не из головы, а из самого дерева: объявления class/struct/record/
#     enum/interface в файлах оболочки.
#
# ПОЧЕМУ КОММЕНТАРИИ ВЫЧЁРКИВАЮТСЯ. Это не удобство, а условие честности. Док-комментарии
# в этом дереве добросовестно объясняют соседей, и почти каждый файл называет в прозе тип,
# на который в коде не ссылается ни разу. Живые примеры на текущем дереве, которые
# наивный grep покрасил бы в красный, а этот прибор не считает ссылками:
#     EditorMouse.cs:13      <c>GraphicsDevice.PresentationParameters</c> ... — в комментарии
#     EditorSheetStep.cs:11  «cannot be constructed without a <c>GraphicsDevice</c>» — там же
#     MapEditorView.cs:160   то же предложение, тот же смысл — там же
#     EditorChrome.cs:54     <see cref="PixelFontMetrics.UiScale"/> — там же
# Прибор печатает счётчик таких вычеркнутых упоминаний отдельной строкой: если он равен
# нулю, значит вычёркивание сломалось и разбору верить нельзя.
#
# ГРАНУЛЯРНОСТЬ — ФАЙЛ, А НЕ ТИП, И ЭТО СОЗНАТЕЛЬНО. Слой назначается файлу. Значит файл,
# сложивший в себя типы двух слоёв, штрафуется через своих читателей — ровно так волна и
# нашла оба сегодняшних нарушения (ShellMode в файле машины режимов, метрики шрифта в файле
# атласа). Плата за это — необходимость держать список файлов ниже в актуальном состоянии,
# и она взимается принудительно: .cs-файл без слоя останавливает прибор с кодом 2, как
# ненайденный маркер останавливает count-chrome.sh. Молча посчитать неправильно нельзя.
#
# --------------------------------------------------------------------------------------
# ПОРОГ РАЗМЕРА: 500 строк. Число не круглое и взято не с потолка — его нарисовало само
# дерево. Отсортируй файлы оболочки по длине: 430 (SpriteEditorLayout), 499
# (SpriteEditorRenderer), потом обрыв — 848, 1159, 1212, 1698. Ниже 500 лежат все файлы,
# про которые можно сказать одним предложением, чем они заняты; выше 500 — ровно четыре,
# и про каждый из четырёх известно, что дел у него больше одного (EditorIcons.cs — таблица
# иконок И маршрутизация кликов; QuarpGame.cs — цикл И роутинг И раскладка; CartSession.cs —
# загрузка И тики И реплеи И save.dat; SpriteEditorSession.cs — модель И undo И PNG).
# Порог поставлен на верхнюю границу «одного дела», как её показало дерево, а не на
# красивое число. Перепин — только строкой здесь и абзацем в отчёте, что изменилось.
#
# ПРЕВЫШЕНИЕ ПОРОГА — ПРЕДУПРЕЖДЕНИЕ, НЕ СМЕРТЬ, и код выхода от него НЕ зависит. Причина
# прямая: размер — подозрение, направление ссылки — доказательство. Файл на 1698 строк
# может быть честным одним делом; ссылка вверх честной не бывает никогда. Смешать их в
# один вердикт значило бы получить прибор, который или молчит про спагетти, или воет на
# длинные файлы, — и в обоих случаях его перестанут слушать.
#
# НА ЧЁМ НАПИСАН РАЗБОР И ПОЧЕМУ ИМЕННО ТАК. Первая редакция прибора разбирала C# питоном
# и на воротах владельца (Windows, Git Bash) не запустилась вовсе: `python3` там —
