  # остаётся headless-тестируемым.
  "SystemTextClipboard.cs|4"   # текстовый буфер обмена машины за ITextClipboard
  "CartSession.cs|4"           # хозяин запущенного картриджа: тики, реплеи, save.dat
  "ShellModeMachine.cs|4"      # переходы между режимами и жизнь сессии
  "SpriteEditorInput.cs|4"     # роутер ввода экрана спрайтов (+EditorShell)
  "MapEditorInput.cs|4"        # роутер ввода экрана карты
  "CodeEditorInput.cs|4"       # роутер ввода экрана кода (клавиши + поток символов)
  "SfxEditorInput.cs|4"        # роутер ввода экрана звука (пиано-ряды, сетки, поля)
  "MusicEditorInput.cs|4"      # роутер ввода экрана музыки (сетка паттернов, флаги, mute/solo, обзор)
  "QuarpGame.cs|4"             # игровой цикл окна
  "Program.cs|4"               # точка входа
)

LAYER_NAMES=("" "документ" "вид" "рендер" "проводка")
# printf считает БАЙТЫ, а кириллица многобайтовая, поэтому колонка слоя не форматируется
# на лету, а лежит уже дополненной до десяти ЗНАКОВ — иначе таблица разъезжается.
LAYER_LABELS=("" "1 документ" "2 вид     " "3 рендер  " "4 проводка")
LAYER_HEADER="слой      "

# --- окружение -----------------------------------------------------------------------------
if ! command -v awk >/dev/null 2>&1; then
  echo "нет awk — разбор C# без него честно не сделать (см. шапку: комментарии и" >&2
  echo "строковые литералы обязаны вычёркиваться, grep этого не умеет)" >&2
  exit 2
fi
if [ ! -d "$SHELL_DIR" ]; then
  echo "нет каталога $SHELL_DIR — дерево не то, что ожидал прибор" >&2
  exit 2
fi

# --- сверка списка с деревом: ни файла без слоя, ни слоя без файла --------------------------
fail_env=0
declare -A LAYER_OF=()
for spec in "${LAYERS[@]}"; do
  f="${spec%%|*}"; l="${spec##*|}"
  if [ ! -f "$SHELL_DIR/$f" ]; then
    echo "в списке слоёв есть $f, а в дереве его нет — файл переименован или удалён;" >&2
    echo "обнови scripts/check-modules.sh, счёт остановлен" >&2
    fail_env=1
  fi
  LAYER_OF["$f"]="$l"
done
for path in "$SHELL_DIR"/*.cs; do
  f="$(basename "$path")"
  if [ -z "${LAYER_OF[$f]+set}" ]; then
    echo "файл без слоя: $f — новый модуль появился, а слоя ему не назначили;" >&2
    echo "допиши строку в LAYERS в scripts/check-modules.sh, счёт остановлен" >&2
    fail_env=1
  fi
done
if [ "$fail_env" -ne 0 ]; then
  echo "ОШИБКА ОКРУЖЕНИЯ: список слоёв и дерево разошлись." >&2
  exit 2
fi

# --- разбор ---------------------------------------------------------------------------------
# awk получает список «файл|слой» через окружение и печатает три вида строк:
#   R<TAB>файл<TAB>слой<TAB>цельслой:символы,...   — строка таблицы
#   V<TAB>файл<TAB>слой<TAB>символ<TAB>цельфайл<TAB>цельслой<TAB>строки — нарушение
#   C<TAB>число                                     — сколько упоминаний вычеркнуто вместе
#                                                     с комментариями/строками (самопроверка)
OUT="$(mktemp)" || exit 2
ERR="$(mktemp)" || exit 2
trap 'rm -f "$OUT" "$ERR"' EXIT
FILES=()
for spec in "${LAYERS[@]}"; do FILES+=("$SHELL_DIR/${spec%%|*}"); done
QUARP_LAYERS="$(printf '%s\n' "${LAYERS[@]}" | sed 's/[ \t]*#.*$//')" \
QUARP_ORDER="$(printf '%s\n' "${LAYERS[@]}" | sed 's/|.*$//')" \
awk -f "$(dirname "$0")/check-modules.awk" "${FILES[@]}" > "$OUT" 2> "$ERR"
rc=$?
if [ "$rc" -ne 0 ]; then
  cat "$ERR" >&2
  echo "ОШИБКА ОКРУЖЕНИЯ: разбор не состоялся." >&2
  exit 2
fi
if [ ! -s "$OUT" ]; then
  cat "$ERR" >&2
  echo "ОШИБКА ОКРУЖЕНИЯ: разбор ничего не напечатал." >&2
  exit 2
fi

# --- печать ---------------------------------------------------------------------------------
echo "=== карта слоёв: файл → слой → на какие слои ссылается ==="
echo "    (цифра перед двоеточием — слой, куда ведёт ссылка; вниз и вбок — норма)"
printf '%s %-26s %s\n' "$LAYER_HEADER" "файл" "ссылается на"
while IFS=$'\t' read -r kind f lvl cell; do
  [ "$kind" = "R" ] || continue
  printf '%s %-26s %s\n' "${LAYER_LABELS[$lvl]}" "$f" "$cell"
done < "$OUT"

echo
echo "=== нарушения направления (ссылка вверх по слоям) ==="
violations=0
while IFS=$'\t' read -r kind f lvl sym home hlvl lines; do
  [ "$kind" = "V" ] || continue
  violations=$((violations + 1))
  printf 'ВВЕРХ  %s (слой %s %s)  →  %s (слой %s %s, %s)  строки %s\n' \
    "$f" "$lvl" "${LAYER_NAMES[$lvl]}" "$sym" "$hlvl" "${LAYER_NAMES[$hlvl]}" "$home" "$lines"
done < "$OUT"
if [ "$violations" -eq 0 ]; then
  echo "нет — все ссылки идут вниз или вбок."
fi

echo
echo "=== переросли порог размера ($SIZE_THRESHOLD строк) — кандидаты на разделение ==="
echo "    (предупреждение, на код выхода НЕ влияет: размер — подозрение, направление — доказательство)"
oversize=0
while IFS= read -r line; do
  n="${line%% *}"; f="${line#* }"
  [ "$n" -gt "$SIZE_THRESHOLD" ] || continue
  oversize=$((oversize + 1))
  base="$(basename "$f")"
  printf '%6d  %-26s слой %s %s\n' "$n" "$base" "${LAYER_OF[$base]}" "${LAYER_NAMES[${LAYER_OF[$base]}]}"
done < <(wc -l "$SHELL_DIR"/*.cs | grep -v ' total$' | sed 's/^ *//' | sort -rn)
if [ "$oversize" -eq 0 ]; then
  echo "нет."
fi

# --- самопроверка разбора --------------------------------------------------------------------
cut_hits="$(awk -F'\t' '$1=="C"{print $2}' "$OUT")"
files_total="$(printf '%s\n' "${LAYERS[@]}" | wc -l | tr -d ' ')"
echo
echo "=== самопроверка разбора ==="
printf 'файлов в списке слоёв: %s; упоминаний типов, вычеркнутых вместе с комментариями и строками: %s\n' \
  "$files_total" "$cut_hits"
if [ "${cut_hits:-0}" -eq 0 ]; then
  echo "НОЛЬ вычеркнутых упоминаний — вычёркивание комментариев сломалось, разбору верить нельзя." >&2
  exit 2
fi
echo "(ноль здесь означал бы сломанное вычёркивание и остановку прибора — см. шапку)"

echo
echo "=== ИТОГ ==="
printf 'Нарушений направления: %d. Файлов сверх порога: %d.\n' "$violations" "$oversize"
if [ "$violations" -ne 0 ]; then
  echo "ВЕРДИКТ: ГРАНИЦЫ НЕ ДЕРЖАТСЯ — есть ссылки вверх по слоям. Стоп и доклад:"
  echo "чинить переносом типа/сменой параметра, а не тем, чтобы дописать слой в список."
  exit 1
fi
echo "ВЕРДИКТ: границы держатся — ни одной ссылки вверх по слоям."
exit 0
