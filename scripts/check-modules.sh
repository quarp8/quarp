# рекламу магазина и выходит с ошибкой. Прибор честно остановился с кодом 2 («разбор не
# состоялся») вместо того, чтобы соврать зелёным, — но прибор, который не бежит там, где
# стоят ворота, вердикта не выносит. Разбор переписан на POSIX awk: он есть и в Git Bash
# (GNU Awk 5.0), и на обоих раннерах CI, и в контейнере. Расширения gawk сознательно не
# используются (ни трёхаргументного match, ни gensub, ни asort, ни RS="^$") — код обязан
# считать одинаково на mawk и на gawk, иначе у факта снова два владельца.
#
# КОДЫ ВЫХОДА: 0 — границы держатся; 1 — есть ссылки вверх по слоям; 2 — ошибка окружения
# (нет awk, дерево не то, файл без слоя, слой без файла, тип объявлен дважды).
